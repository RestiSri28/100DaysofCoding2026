public class Day02 {
    public static void main(String[] args) {

        // Menampilkan judul menggunakan println()
        System.out.println(" BIODATA DIRI");

        // println() digunakan untuk menampilkan teks
        // dan langsung pindah ke baris berikutnya
        System.out.println("Nama       : Resti SriAstuti");
        System.out.println("Jurusan    : Teknik Informatika");
        System.out.println("Universitas: Universitas Sulawesi Barat");

        // print digunakan untuk menampilkan teks
        // tanpa langsung pindah ke baris berikutnya
        System.out.print("Status     : ");
        System.out.print("Mahasiswa");

        // printf() digunakan untuk menampilkan teks dengan format tertentu
        System.out.printf("\nUmur       : %d tahun", 18);

        // Kembali menggunakan println()
        System.out.println("\nHobi       : Membaca");
    }
}
