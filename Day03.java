public class Day03 {
    public static void main(String[] args) {

        // \n digunakan untuk membuat baris baru
        System.out.println("Halo, nama saya Resti.\nSaya sedang belajar Java.");

        // \t digunakan untuk membuat jarak seperti tab
        System.out.println("Nama\t: Resti Sri Astuti");
        System.out.println("Prodi\t: Teknik Informatika");

        // \" digunakan untuk menampilkan tanda kutip
        System.out.println("Saya berkata, \"Saya sedang belajar Java.\"");

        // \\ digunakan untuk menampilkan tanda backslash
        System.out.println("Contoh backslash: \\");

        // \b digunakan untuk menghapus satu karakter sebelumnya
        System.out.println("Halo\b!");

        // \r digunakan untuk kembali ke awal baris
        System.out.println("Java\rBelajar");

    }
}
