public class Day05 {
    public static void main(String[] args) {

        // Mempelajari tipe data pecahan
        // double digunakan untuk menyimpan bilangan pecahan
        // float digunakan untuk menyimpan bilangan pecahan
        // dengan ukuran yang lebih kecil dibandingkan double

        double tinggiBadan = 150.5;
        float beratBadan = 50.5f;

        // Menampilkan nilai ke layar
        System.out.println("DATA BILANGAN PECAHAN");
        System.out.println("Tinggi Badan : " + tinggiBadan + " cm");
        System.out.println("Berat Badan  : " + beratBadan + " kg");

        // Kesimpulan
        System.out.println("\nSaya sedang belajar tipe data double dan float.");
    }
}
