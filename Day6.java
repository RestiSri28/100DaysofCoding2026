public class Day06 {
    public static void main(String[] args) {

        // Mempelajari tipe data char dan boolean

        // char digunakan untuk menyimpan satu karakter
        char jenisKelamin = 'P';

        // boolean digunakan untuk menyimpan nilai true atau false
        boolean mahasiswaAktif = true;

        // Menampilkan nilai ke layar
        System.out.println("DATA KARAKTER DAN BOOLEAN");
        System.out.println("Jenis Kelamin   : " + jenisKelamin);
        System.out.println("Mahasiswa Aktif : " + mahasiswaAktif);

        // Kesimpulan
        System.out.println("\nSaya sedang belajar tipe data char dan boolean.");
    }
}
